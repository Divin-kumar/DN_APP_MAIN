import { test, expect } from '@playwright/test';
import { seedGuest } from './fixtures.js';

test('PDF Studio keeps style separate from format and blocks stale exports', async ({ page }) => {
  const errors = await seedGuest(page);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/events/moment-one/pdf');
  const studio = page.locator('.dn-pdf-studio-page');
  await expect(studio).toBeVisible();
  await expect(studio.getByRole('combobox', { name: 'PDF story format' })).toHaveValue('journey');
  await expect(studio.getByRole('button', { name: 'PDF design Editorial' })).toHaveAttribute('aria-pressed', 'true');
  await expect(studio.getByRole('img', { name: 'Rendered PDF page 1' })).toBeVisible();
  const hashPage = () => page.evaluate(async () => {
    const url = document.querySelector('.dn-pdf-preview-page img')?.src;
    if (!url) return '';
    const bytes = await (await fetch(url)).arrayBuffer();
    const result = new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
    return Array.from(result, (value) => value.toString(16).padStart(2, '0')).join('');
  });
  const baselinePage = await hashPage();
  const unchangedRecords = await page.evaluate(() => localStorage.getItem('dn_guest_eventGroups'));
  await studio.getByRole('button', { name: 'PDF design Heritage' }).click();
  await expect(studio.getByRole('combobox', { name: 'PDF story format' })).toHaveValue('journey');
  await expect(studio.getByRole('button', { name: 'Download customized PDF' })).toBeDisabled();
  await studio.getByRole('button', { name: 'Update preview' }).click();
  await expect(studio.getByRole('button', { name: 'Download customized PDF' })).toBeEnabled({ timeout: 20000 });
  await expect(studio.getByRole('button', { name: 'PDF design Heritage' })).toHaveAttribute('aria-pressed', 'true');
  const heritagePage = await hashPage();
  expect(heritagePage).not.toBe(baselinePage);
  await studio.getByRole('button', { name: 'Toggle PDF page thumbnails' }).click();
  await expect(studio.getByRole('navigation', { name: 'PDF page thumbnails' })).toBeVisible();
  await studio.getByRole('button', { name: 'Zoom in PDF preview' }).click();
  await expect(studio.getByRole('button', { name: 'Reset PDF preview zoom' })).toContainText('125%');
  await studio.getByRole('button', { name: 'Reset PDF preview zoom' }).click();
  await expect(studio.getByRole('button', { name: 'Reset PDF preview zoom' })).toContainText('100%');
  await studio.getByRole('button', { name: 'Open full-screen PDF preview' }).click();
  const dialog = studio.getByRole('dialog', { name: 'Full-screen PDF preview' });
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Close full-screen PDF preview' }).click();
  await expect(dialog).not.toBeVisible();
  await studio.getByRole('button', { name: 'PDF design Minimal' }).click();
  await studio.getByRole('button', { name: 'Use saved default' }).click();
  await expect(studio.getByRole('button', { name: 'PDF design Editorial' })).toHaveAttribute('aria-pressed', 'true');
  await expect(studio.getByRole('button', { name: 'Download customized PDF' })).toBeDisabled();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  expect(overflow).toBe(false);
  expect(await page.evaluate(() => localStorage.getItem('dn_guest_eventGroups'))).toBe(unchangedRecords);
  expect(errors).toEqual([]);
});
