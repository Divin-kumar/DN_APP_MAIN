import { test, expect } from '@playwright/test';
import { seedGuest, activityDetailAction } from './fixtures.js';

test.use({ timezoneId:'Asia/Kolkata' });
for(const width of [320,1280]) test(`new entries capture local time once and cleared drafts stay empty at ${width}px`,async({page})=>{
  test.setTimeout(60000);
  await page.setViewportSize({width,height:900});
  await page.clock.install({time:new Date('2026-10-29T04:45:00Z')});
  const errors=await seedGuest(page);
  await page.goto('/events?create=event');
  const dialog=page.getByRole('dialog');
  await dialog.locator('.dn-form-disclosure > summary').click();
  await expect(dialog.getByLabel('Moment time',{exact:true})).toHaveValue('10:15');
  await dialog.getByRole('button',{name:'Clear moment time',exact:true}).click();
  await dialog.getByRole('textbox',{name:'Moment name',exact:true}).fill('Manually untimed Moment');
  await page.evaluate(async()=>{const app=(await import('/src/store/useAppStore.js')).default;app.setState({preferences:{...app.getState().preferences,defaultEventType:'Birthday'}});});
  await expect(dialog.getByRole('textbox',{name:'Moment name',exact:true})).toHaveValue('Manually untimed Moment');
  await page.clock.setSystemTime(new Date('2026-10-29T04:50:00Z'));
  await expect(dialog.getByLabel('Moment time',{exact:true})).toHaveValue('');
  await dialog.getByRole('button',{name:'Save Event',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('dn_guest_eventGroups')).find(x=>x.name==='Manually untimed Moment').time||'')).toBe('');
  await page.goto('/financials/transactions?create=expense');
  await dialog.locator('.dn-form-disclosure > summary').click();
  await expect(dialog.getByLabel('Transaction time',{exact:true})).toHaveValue('10:20');
  await dialog.getByRole('button',{name:'Clear transaction time',exact:true}).click();
  await dialog.getByRole('textbox',{name:'Title *',exact:true}).fill('Manually untimed purchase');
  await dialog.getByRole('spinbutton').fill('25');
  await dialog.getByRole('radio',{name:'Cash',exact:true}).check();
  await page.evaluate(async()=>{const app=(await import('/src/store/useAppStore.js')).default;app.setState({preferences:{...app.getState().preferences,defaultExpenseCategory:'Travel'}});});
  await expect(dialog.getByRole('textbox',{name:'Title *',exact:true})).toHaveValue('Manually untimed purchase');
  await expect(dialog.getByLabel('Transaction time',{exact:true})).toHaveValue('');
  await dialog.getByRole('button',{name:'Add Transaction',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('dn_guest_expenses')).find(x=>x.name==='Manually untimed purchase').time||'')).toBe('');
  await page.goto('/events/moment-one/activities?create=activity');
  await dialog.locator('.dn-form-disclosure > summary').click();
  await expect(dialog.getByLabel('Activity time',{exact:true})).toHaveValue('10:20');
  await dialog.getByRole('button',{name:'Clear activity time',exact:true}).click();
  await dialog.getByPlaceholder('Entry title',{exact:true}).fill('Manually untimed activity');
  await dialog.getByRole('button',{name:'Add entry',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('dn_guest_eventGroups'))[0].activities.find(x=>x.title==='Manually untimed activity').time)).toBe('');
  const open=async()=>{
    await page.getByRole('button',{name:'Open quick create menu',exact:true}).click();
    await page.getByRole('button',{name:'Activity',exact:true}).click();
  };
  await open();await expect(dialog.getByLabel('Activity time',{exact:true})).toHaveValue('10:20');
  await page.clock.setSystemTime(new Date('2026-10-29T04:53:00Z'));
  await expect(dialog.getByLabel('Activity time',{exact:true})).toHaveValue('10:20');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  await open();await expect(dialog.getByLabel('Activity time',{exact:true})).toHaveValue('10:23');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  expect(errors).toEqual([]);
});

test('editing existing untimed Moments, Activities and transactions does not insert the current clock',async({page})=>{
  await page.clock.install({time:new Date('2026-10-29T04:45:00Z')});
  const errors=await seedGuest(page);
  await page.goto('/events');
  await page.getByRole('button',{name:/Actions for Weekend in Ooty/}).click();
  await page.getByRole('menuitem',{name:'Edit',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await expect(dialog.getByLabel('Moment time',{exact:true})).toHaveValue('');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.goto('/events/moment-one/activities/shared');
  await activityDetailAction(page,'Edit');
  await expect(dialog.getByLabel('Activity time',{exact:true})).toHaveValue('');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.goto('/financials');
  await page.locator('.dn-transaction-card').filter({hasText:'Room deposit'}).locator('.dn-transaction-copy > strong').click();
  await page.getByRole('menuitem',{name:'Edit',exact:true}).click();
  await expect(dialog.getByLabel('Transaction time',{exact:true})).toHaveValue('');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  expect(errors).toEqual([]);
});
